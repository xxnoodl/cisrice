import {test,expect} from "@playwright/test";

test("local portfolio creation, isolated brand settings, account registration and logout", async({page})=>{
  const email=process.env.CISRICE_E2E_EMAIL;
  const password=process.env.CISRICE_E2E_PASSWORD;
  if(!email||!password)throw new Error("Run via the Linux verifier with --e2e; isolated fixture credentials are required.");
  await page.goto("/");
  await page.getByLabel("Email",{exact:true}).fill(email);
  await page.getByLabel("Password",{exact:true}).fill(password);
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await page.getByRole("link",{name:"Portfolio",exact:true}).click();
  await page.getByLabel("Workspace name",{exact:true}).fill("E2E Portfolio");
  await page.getByRole("button",{name:"Create workspace",exact:true}).click();
  await page.getByLabel("Niche name",{exact:true}).fill("Technology");
  await page.getByRole("button",{name:"Create niche",exact:true}).click();
  await page.getByLabel("New brand name",{exact:true}).fill("E2E Brand A");
  await page.getByRole("button",{name:"Create brand",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Brand identity and style"})).toBeVisible();
  const brandA=await page.getByRole("combobox",{name:"Brand",exact:true}).inputValue();
  await page.getByRole("textbox",{name:"Description",exact:true}).fill("Independent first brand");
  await page.getByRole("button",{name:"Save brand identity",exact:true}).click();
  await page.getByRole("textbox",{name:"Voice and editorial preferences",exact:true}).fill("Concise and factual");
  await page.getByRole("textbox",{name:"Audience",exact:true}).fill("Creators");
  await page.getByLabel("Colors (comma-separated #RRGGBB)",{exact:true}).fill("#112233");
  await page.getByRole("button",{name:"Save style guide",exact:true}).click();
  await expect(page.getByRole("form",{name:"Save style guide"}).getByRole("status")).toHaveText("Saved");
  await page.getByLabel("Account handle",{exact:true}).fill("@e2e_fixture");
  await page.getByRole("button",{name:"Register account",exact:true}).click();
  await expect(page.getByRole("cell",{name:"REGISTERED",exact:true})).toBeVisible();
  await page.getByLabel("New brand name",{exact:true}).fill("E2E Brand B");
  await page.getByRole("button",{name:"Create brand",exact:true}).click();
  await expect(page.getByLabel("Brand name",{exact:true})).toHaveValue("E2E Brand B");
  await expect(page.getByRole("textbox",{name:"Voice and editorial preferences",exact:true})).toHaveValue("");
  await expect(page.getByText("No platform accounts visible in this brand.")).toBeVisible();
  await page.getByRole("combobox",{name:"Brand",exact:true}).selectOption(brandA);
  await expect(page.getByRole("textbox",{name:"Voice and editorial preferences",exact:true})).toHaveValue("Concise and factual");
  await page.getByRole("link",{name:"Settings",exact:true}).click();
  await expect(page.getByRole("textbox",{name:"Voice and editorial preferences",exact:true})).toHaveValue("Concise and factual");
  await page.getByRole("link",{name:"Portfolio",exact:true}).click();
  await page.reload();
  await expect(page.getByLabel("Brand name",{exact:true})).toHaveValue("E2E Brand A");
  await expect(page.getByRole("cell",{name:"REGISTERED",exact:true})).toBeVisible();
  await expect(page.getByRole("cell",{name:"account.registered",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Sign in to Cisrice"})).toBeVisible();
});
